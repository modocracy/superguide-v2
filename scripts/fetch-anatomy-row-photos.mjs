// Downloads the wiki's highlighted image for every Anatomy row of dist/data/enemy-anatomy.js that has
// no matching site photo: the main pools, rows the calculator merges or leaves out, and parts whose
// site photo is not one of the row's current wiki images (the wiki renamed or replaced it). The first
// image of the row (front, else side, rear, ...) is saved as WebP (quality 90, via Pillow) with a 320px
// thumbnail, added to scripts/anatomy-webp.json and listed in dist/data/anatomy-row-images.js with the
// PNG hashes. Rows that already have a photo there are kept.
// Usage: node scripts/build-enemy-anatomy.mjs && node scripts/fetch-anatomy-row-photos.mjs
//        (needs network and python with Pillow)
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { enemyAnatomy } from '../dist/data/enemy-anatomy.js';
import { sitePhoto } from '../dist/core/anatomy.js';

const root = new URL('../', import.meta.url);
const API = 'https://helldivers.wiki.gg/api.php';
const UA = 'HD2FieldGuide/2.0 (fan site data check; contact via github modocracy)';
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const slug = text => text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const today = new Date().toISOString().slice(0, 10);

const manifestUrl = new URL('scripts/anatomy-webp.json', root);
const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'));
const moduleUrl = new URL('dist/data/anatomy-row-images.js', root);
const previous = await import(moduleUrl).then(module => module.anatomyRowImages, () => ({}));

const get = async (url, as = 'json', tries = 3) => {
  try {
    const res = await fetch(url, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(30000) });
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    await new Promise(resolve => setTimeout(resolve, 250));
    return as === 'json' ? await res.json() : Buffer.from(await res.arrayBuffer());
  } catch (error) {
    if (tries <= 1) throw error;
    await new Promise(resolve => setTimeout(resolve, 2000));
    return get(url, as, tries - 1);
  }
};
const imageInfo = async (file, width) => {
  const params = new URLSearchParams({ action: 'query', format: 'json', formatversion: '2', prop: 'imageinfo', iiprop: 'url|size', iiurlwidth: String(width), titles: `File:${file}` });
  const info = (await get(`${API}?${params}`)).query.pages[0].imageinfo?.[0];
  if (!info) throw new Error(`No wiki file ${file}`);
  return info;
};
const toWebp = (png, webp) => execFileSync('python', ['-c', 'import sys; from PIL import Image; Image.open(sys.argv[1]).save(sys.argv[2], "WEBP", quality=90, method=6)', png, webp]);

async function photo(enemyId, rowName, file) {
  const big = await imageInfo(file, 800);
  const small = await imageInfo(file, 320);
  const name = `row-${enemyId}-${slug(rowName)}`;
  const hashes = {};
  for (const [suffix, url] of [['', big.thumburl], ['-thumb', small.thumburl]]) {
    const png = await get(url, 'bytes');
    const pngPath = fileURLToPath(new URL(`dist/assets/anatomy/${name}${suffix}.png`, root));
    const webpPath = pngPath.replace(/\.png$/, '.webp');
    await writeFile(pngPath, png);
    toWebp(pngPath, webpPath);
    execFileSync('python', ['-c', 'import os, sys; os.remove(sys.argv[1])', pngPath]);
    manifest[`./assets/anatomy/${name}${suffix}.webp`] = { sha256: sha(await readFile(webpPath)), sourceSha256: sha(png) };
    hashes[suffix ? 'thumbnailSha256' : 'sha256'] = sha(png);
  }
  return {
    src: `./assets/anatomy/${name}.webp`, thumbnail: `./assets/anatomy/${name}-thumb.webp`, title: file,
    source: `https://helldivers.wiki.gg/wiki/File:${file.replaceAll(' ', '_')}`, originalUrl: big.url, renderedUrl: big.thumburl, thumbnailUrl: small.thumburl,
    width: big.thumbwidth, height: big.thumbheight, thumbnailWidth: small.thumbwidth, thumbnailHeight: small.thumbheight,
    sha256: hashes.sha256, thumbnailSha256: hashes.thumbnailSha256, retrievedAt: today,
  };
}

const images = structuredClone(previous);
let added = 0;
for (const [enemyId, enemy] of Object.entries(enemyAnatomy)) {
  for (const row of enemy.rows) {
    const file = row.images[0];
    if (!file || sitePhoto(enemyId, row) || images[enemyId]?.[row.name]?.title === file) continue;
    (images[enemyId] ||= {})[row.name] = await photo(enemyId, row.name, file);
    added++;
    console.log(`${enemyId} / ${row.name}: ${file}`);
  }
}
await writeFile(manifestUrl, JSON.stringify(Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))), null, 2) + '\n');
await writeFile(moduleUrl, `// Generated by scripts/fetch-anatomy-row-photos.mjs: the wiki's highlighted image for Anatomy rows
// (dist/data/enemy-anatomy.js) without a matching site photo, keyed by enemy id and wiki row name.
// sha256/thumbnailSha256 are the Wiki PNGs; the served files are their WebP (quality 90) encodings.
export const anatomyRowImages = ${JSON.stringify(images, null, 2)};
`);
console.log(`${added} photos added`);
