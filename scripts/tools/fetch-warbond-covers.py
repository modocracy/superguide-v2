"""Download warbond cover art from the Helldivers Wiki as small WebP thumbnails.

Reads the infobox `image=` of each warbond in db/source/wiki_warbonds.json, asks the
wiki API for a 240 px wide thumbnail, and writes dist/assets/warbonds/<id>.webp plus
dist/data/warbond-images.js. Ids follow scripts/build-warbonds.mjs (warbondId).

Usage: python scripts/tools/fetch-warbond-covers.py   (requires Pillow with WebP)
"""
import hashlib, io, json, pathlib, re, time, urllib.parse, urllib.request

from PIL import Image

root = pathlib.Path(__file__).resolve().parents[2]
out_dir = root / 'dist' / 'assets' / 'warbonds'
module = root / 'dist' / 'data' / 'warbond-images.js'
API = 'https://helldivers.wiki.gg/api.php'
UA = 'HD2FieldGuide/2.0 (fan site data check; contact via github modocracy)'
WIDTH = 240


def get(url):
    request = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def warbond_id(title):
    base = re.sub(r'\s+(?:(?:Premium|Legendary)\s+)?Warbond$', '', title)
    return re.sub(r'^-|-$', '', re.sub(r'[^a-z0-9]+', '-', re.sub(r"['’]", '', base.lower())))


pages = json.loads((root / 'db' / 'source' / 'wiki_warbonds.json').read_text(encoding='utf-8'))['pages']
files = {}
for title, page in pages.items():
    match = re.search(r'\n\s*\|\s*image\s*=\s*([^\n|]*)', page['wikitext'] or '')
    if match and match.group(1).strip():
        files[title] = match.group(1).strip()

info = {}
titles = sorted(set(files.values()))
for start in range(0, len(titles), 50):
    batch = titles[start:start + 50]
    query = urllib.parse.urlencode({'action': 'query', 'format': 'json', 'prop': 'imageinfo', 'iiprop': 'url|sha1|size',
                                    'iiurlwidth': WIDTH, 'titles': '|'.join('File:' + t for t in batch)})
    data = json.loads(get(f'{API}?{query}'))
    normalized = {n['to']: n['from'] for n in data['query'].get('normalized', [])}
    for p in data['query']['pages'].values():
        if p.get('imageinfo'):
            info[normalized.get(p['title'], p['title'])[5:]] = p['imageinfo'][0]
    time.sleep(0.3)

out_dir.mkdir(parents=True, exist_ok=True)
entries, missing = {}, []
for title in sorted(pages):
    meta = info.get(files.get(title))
    if not meta:
        missing.append(title); continue
    raw = get(meta.get('thumburl') or meta['url'])
    time.sleep(0.2)
    with Image.open(io.BytesIO(raw)) as image:
        image = image.convert('RGB')
        if image.width > WIDTH:
            image = image.resize((WIDTH, round(image.height * WIDTH / image.width)), Image.LANCZOS)
        buffer = io.BytesIO()
        image.save(buffer, 'WEBP', quality=78, method=6)
        width, height = image.size
    wid = warbond_id(title)
    target = out_dir / f'{wid}.webp'
    target.write_bytes(buffer.getvalue())
    entries[wid] = {
        'src': f'./assets/warbonds/{target.name}', 'width': width, 'height': height,
        'file': files[title], 'source': 'https://helldivers.wiki.gg/wiki/File:' + urllib.parse.quote(files[title].replace(' ', '_')),
        'sourceSha1': meta.get('sha1'), 'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
    }

body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}' for k, v in sorted(entries.items()))
module.write_text('// Generated by scripts/tools/fetch-warbond-covers.py from Helldivers Wiki warbond cover art.\n'
                  f'export const warbondImages = {{\n{body},\n}};\n', encoding='utf-8', newline='\n')
print(f'{len(entries)} covers written; missing: {missing}')
