"""Download warbond cover art from the Helldivers Wiki as WebP files.

Default: for every warbond in db/source/wiki_warbonds.json, a 240 px wide thumbnail of the
infobox `image=` → dist/assets/warbonds/<id>.webp plus dist/data/warbond-images.js.

--latest-large: only for the warbond in the "latest release" banner (latestWarbondId of
dist/data/warbonds.js, so run scripts/build-warbonds.mjs first) a ~1600 px wide version →
dist/assets/warbonds/<id>-large.webp plus dist/data/warbond-banner-images.js. Never upscales
past the original; lowers WebP quality step by step to stay within MAX_BYTES. The small
covers are left untouched in this mode.

Ids follow scripts/build-warbonds.mjs (warbondId). The wiki rejects browser User-Agents.
Usage: python scripts/tools/fetch-warbond-covers.py [--latest-large]   (requires Pillow with WebP)
"""
import hashlib, io, json, pathlib, re, subprocess, sys, time, urllib.parse, urllib.request

from PIL import Image

root = pathlib.Path(__file__).resolve().parents[2]
out_dir = root / 'dist' / 'assets' / 'warbonds'
API = 'https://helldivers.wiki.gg/api.php'
UA = 'HD2FieldGuide/2.0 (fan site data check; contact via github modocracy)'
WIDTH = 240
LARGE_WIDTH = 1600  # the banner spans the full content width (up to ~1240 px CSS), cropped to a wide strip
MAX_BYTES = 120_000


def get(url):
    request = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def warbond_id(title):
    base = re.sub(r'\s+(?:(?:Premium|Legendary)\s+)?Warbond$', '', title)
    return re.sub(r'^-|-$', '', re.sub(r'[^a-z0-9]+', '-', re.sub(r"['’]", '', base.lower())))


def cover_files(pages):
    files = {}
    for title, page in pages.items():
        match = re.search(r'\n\s*\|\s*image\s*=\s*([^\n|]*)', page['wikitext'] or '')
        if match and match.group(1).strip():
            files[title] = match.group(1).strip()
    return files


def image_info(names, width):
    info = {}
    names = sorted(set(names))
    for start in range(0, len(names), 50):
        batch = names[start:start + 50]
        query = urllib.parse.urlencode({'action': 'query', 'format': 'json', 'prop': 'imageinfo', 'iiprop': 'url|sha1|size',
                                        'iiurlwidth': width, 'titles': '|'.join('File:' + t for t in batch)})
        data = json.loads(get(f'{API}?{query}'))
        normalized = {n['to']: n['from'] for n in data['query'].get('normalized', [])}
        for p in data['query']['pages'].values():
            if p.get('imageinfo'):
                info[normalized.get(p['title'], p['title'])[5:]] = p['imageinfo'][0]
        time.sleep(0.3)
    return info


def entry(target, name, meta, width, height):
    return {
        'src': f'./assets/warbonds/{target.name}', 'width': width, 'height': height,
        'file': name, 'source': 'https://helldivers.wiki.gg/wiki/File:' + urllib.parse.quote(name.replace(' ', '_')),
        'sourceSha1': meta.get('sha1'), 'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
    }


def write_module(path, export, header, entries):
    body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}' for k, v in sorted(entries.items()))
    path.write_text(f'// Generated by scripts/tools/fetch-warbond-covers.py {header}\n'
                    f'export const {export} = {{\n{body},\n}};\n', encoding='utf-8', newline='\n')


def small_covers(pages):
    files = cover_files(pages)
    info = image_info(files.values(), WIDTH)
    out_dir.mkdir(parents=True, exist_ok=True)
    entries, missing = {}, []
    for title in sorted(pages):
        meta = info.get(files.get(title))
        if not meta:
            missing.append(title); continue
        raw = get(meta.get('thumburl') or meta['url'])
        time.sleep(0.2)
        with Image.open(io.BytesIO(raw)) as image:
            image = image.convert('RGB')
            if image.width > WIDTH:
                image = image.resize((WIDTH, round(image.height * WIDTH / image.width)), Image.LANCZOS)
            buffer = io.BytesIO()
            image.save(buffer, 'WEBP', quality=78, method=6)
            width, height = image.size
        target = out_dir / f'{warbond_id(title)}.webp'
        target.write_bytes(buffer.getvalue())
        entries[warbond_id(title)] = entry(target, files[title], meta, width, height)
    write_module(root / 'dist' / 'data' / 'warbond-images.js', 'warbondImages', 'from Helldivers Wiki warbond cover art.', entries)
    print(f'{len(entries)} covers written; missing: {missing}')


def latest_large(pages):
    latest = subprocess.run(['node', '--input-type=module', '-e',
                             'import { latestWarbondId } from "./dist/data/warbonds.js"; console.log(latestWarbondId ?? "")'],
                            cwd=root, capture_output=True, text=True, check=True).stdout.strip()
    title = next((t for t in pages if warbond_id(t) == latest), None)
    if not title:
        sys.exit(f'latestWarbondId {latest!r} has no page in the snapshot')
    name = cover_files(pages).get(title)
    meta = image_info([name], LARGE_WIDTH).get(name) if name else None
    if not meta:
        sys.exit(f'No cover image for {title}')
    raw = get(meta.get('thumburl') or meta['url'])
    with Image.open(io.BytesIO(raw)) as image:
        image = image.convert('RGB')
        if image.width > LARGE_WIDTH:  # never upscale: a smaller original stays at its own size
            image = image.resize((LARGE_WIDTH, round(image.height * LARGE_WIDTH / image.width)), Image.LANCZOS)
        for quality in range(70, 40, -5):
            buffer = io.BytesIO()
            image.save(buffer, 'WEBP', quality=quality, method=6)
            if buffer.tell() <= MAX_BYTES:
                break
        width, height = image.size
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f'{latest}-large.webp'
    target.write_bytes(buffer.getvalue())
    write_module(root / 'dist' / 'data' / 'warbond-banner-images.js', 'warbondBannerImages',
                 '--latest-large from Helldivers Wiki warbond cover art (latest warbond only).',
                 {latest: {**entry(target, name, meta, width, height), 'quality': quality}})
    print(f'{target.name}: {width}x{height}, {target.stat().st_size} bytes, quality {quality} (original {meta.get("width")}x{meta.get("height")})')


if __name__ == '__main__':
    snapshot = json.loads((root / 'db' / 'source' / 'wiki_warbonds.json').read_text(encoding='utf-8'))['pages']
    if '--latest-large' in sys.argv:
        latest_large(snapshot)
    else:
        small_covers(snapshot)
